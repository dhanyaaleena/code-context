import { execFile } from 'child_process';
import * as path from 'path';
import { CodeAuthor, HistoryEvent } from './types';

const UNIT = '\x1f';
const REC = '\x1e';
/** Trailers and sign-offs are bureaucracy, not reasons. */
const TRAILER_RE = /^(co-authored-by|signed-off-by|reviewed-by|change-id|generated (with|by)|🤖)/i;
const AI_RE = /\b(claude|copilot|codex|cursor|ai[- ]assisted|ai[- ]generated|generated by)\b/i;
const PR_RE = /#(\d+)/;

/**
 * `git log -L :symbol:file` is not cheap on a large repository with deep
 * history, so the budget has to be generous. A timeout returns empty rather
 * than throwing: the panel then shows deterministic context without history,
 * which is the documented degraded path.
 */
function run(args: string[], cwd: string, timeout = 20_000): Promise<string> {
  return new Promise((resolve) => {
    execFile('git', args, { cwd, timeout, maxBuffer: 16 * 1024 * 1024 }, (err, stdout) =>
      resolve(err ? '' : stdout)
    );
  });
}

/** `run`, with `input` written to the command's stdin — for `blame --contents -`. */
function runWithInput(args: string[], cwd: string, input: string, timeout = 10_000): Promise<string> {
  return new Promise((resolve) => {
    const child = execFile('git', args, { cwd, timeout, maxBuffer: 16 * 1024 * 1024 }, (err, stdout) =>
      resolve(err ? '' : stdout)
    );
    child.stdin?.on('error', () => undefined);
    child.stdin?.end(input);
  });
}

export async function repoRootFor(cwd: string): Promise<string | undefined> {
  const out = (await run(['rev-parse', '--show-toplevel'], cwd)).trim();
  return out || undefined;
}

export async function headSha(cwd: string): Promise<string> {
  return (await run(['rev-parse', '--short', 'HEAD'], cwd)).trim();
}

export async function isDirty(cwd: string, file: string): Promise<boolean> {
  const out = await run(['status', '--porcelain', '--', file], cwd, 5000);
  return out.trim().length > 0;
}

/**
 * Prefers `git log -L :symbol:file`, which is genuine symbol-scoped history
 * rather than file-scoped noise. Falls back to file history when -L cannot
 * locate the funcname (it relies on git's own funcname heuristics).
 */
export async function symbolHistory(
  repoRoot: string,
  file: string,
  symbolName: string,
  limit = 8
): Promise<{ events: HistoryEvent[]; source: 'symbol' | 'file' | 'none'; older: number; all: HistoryEvent[] }> {
  const rel = path.relative(repoRoot, file) || file;
  // The body carries the reason; the subject usually only carries the what.
  // %aN, not %an: it honours .mailmap, as blame does, so one person is one name.
  const fmt = ['%h', '%aN', '%aI', '%s', '%b'].join(UNIT) + REC;

  const scoped = await run(
    ['log', '-L', `:${symbolName}:${rel}`, '--no-patch', `--pretty=format:${fmt}`],
    repoRoot
  );
  if (scoped.trim()) {
    const all = parse(scoped);
    return { ...trim([...all], limit, 'symbol'), all };
  }

  const fileLog = await run(
    ['log', '--follow', `--pretty=format:${fmt}`, '--', rel],
    repoRoot
  );
  if (fileLog.trim()) {
    const all = parse(fileLog);
    return { ...trim([...all], limit, 'file'), all };
  }

  return { events: [], source: 'none', older: 0, all: [] };
}

/**
 * Keep the most recent `limit` changes, but always keep the oldest one too.
 *
 * The commit that introduced a symbol is the only one that states why it was
 * built at all; every commit after it explains an adjustment. Dropping it
 * because it fell off the end of a recency window loses the one piece of
 * evidence the question "why does this exist" actually needs.
 */
function trim(
  all: HistoryEvent[],
  limit: number,
  source: 'symbol' | 'file'
): { events: HistoryEvent[]; source: 'symbol' | 'file'; older: number } {
  if (all.length <= limit) {
    if (all.length) {
      all[0].origin = true;
    }
    return { events: all, source, older: 0 };
  }
  const first = all[0];
  first.origin = true;
  const recent = all.slice(-(limit - 1));
  return { events: [first, ...recent], source, older: all.length - limit };
}

function parse(out: string): HistoryEvent[] {
  return out
    .split(REC)
    .filter((r) => r.includes(UNIT))
    .map((record) => {
      const [sha, author, date, subject, body] = record.replace(/^\s+/, '').split(UNIT);
      return {
        sha,
        author,
        date,
        subject,
        body: cleanBody(body),
        pr: PR_RE.exec(subject)?.[1],
        aiAssisted: AI_RE.test(subject)
      };
    })
    .reverse(); // oldest first, so the spine reads left to right
}

/** The prose of a commit message, minus the trailers and the diff chatter. */
function cleanBody(body: string | undefined): string | undefined {
  if (!body) {
    return undefined;
  }
  const kept = body
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !TRAILER_RE.test(l))
    .join(' ')
    .trim();
  return kept ? kept.slice(0, 400) : undefined;
}

/**
 * Who wrote this code: each person's share of the lines as they stand now
 * (blame over the editor's buffer, so unsaved edits count as uncommitted), and
 * how many of the symbol's commits were theirs. Someone who changed the function
 * but whose lines have since been rewritten still appears, with no lines.
 */
export async function symbolAuthors(
  repoRoot: string,
  file: string,
  startLine: number,
  endLine: number,
  contents: string,
  commits: HistoryEvent[],
  scoped: boolean
): Promise<{ authors: CodeAuthor[]; uncommittedLines: number }> {
  const rel = path.relative(repoRoot, file) || file;
  const out = await runWithInput(
    ['blame', '--line-porcelain', '-L', `${startLine + 1},${endLine + 1}`, '--contents', '-', '--', rel],
    repoRoot,
    contents
  );

  const byName = new Map<string, CodeAuthor>();
  const get = (name: string) => {
    let a = byName.get(name);
    if (!a) {
      a = { name, lines: 0, commits: 0, created: false };
      byName.set(name, a);
    }
    return a;
  };

  let uncommittedLines = 0;
  let uncommitted = false;
  for (const line of out.split('\n')) {
    if (/^[0-9a-f]{40} \d+ \d+/.test(line)) {
      uncommitted = /^0{40} /.test(line);
    } else if (line.startsWith('author ')) {
      if (uncommitted) {
        uncommittedLines++;
      } else {
        get(line.slice(7).trim()).lines++;
      }
    }
  }

  // Commit counts only mean "changed this function" when the history is symbol-scoped.
  if (scoped) {
    for (const c of commits) {
      get(c.author).commits++;
    }
    if (commits.length) {
      get(commits[0].author).created = true;
    }
  }

  const authors = [...byName.values()].sort(
    (a, b) => b.lines - a.lines || b.commits - a.commits || a.name.localeCompare(b.name)
  );
  return { authors, uncommittedLines };
}

export async function showCommit(repoRoot: string, sha: string): Promise<string> {
  return (await run(['show', '--stat', '--patch', sha], repoRoot)) || `No output for ${sha}`;
}

/**
 * Files that keep being committed alongside this one. Co-change is a genuine
 * feature signal — it captures coupling that the import graph never sees.
 */
export async function coChangedFiles(
  repoRoot: string,
  file: string,
  limit = 40
): Promise<{ file: string; commits: number }[]> {
  const rel = path.relative(repoRoot, file) || file;

  // `git log --name-only -- <path>` only ever lists <path>, so the commits that
  // touched this file have to be resolved first, then expanded.
  const shas = (await run(['log', `-n${limit}`, '--format=%H', '--', rel], repoRoot))
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter(Boolean);
  if (!shas.length) {
    return [];
  }

  const out = await run(
    ['show', '--name-only', '--format=%x00', '--no-renames', ...shas],
    repoRoot
  );

  // A commit touching half the repository — an initial import, a mass rename, a
  // merge — says nothing about coupling and drowns the real signal in lockfiles
  // and config. Only focused commits count as evidence that two files belong together.
  const BULK_COMMIT = 20;

  const counts = new Map<string, number>();
  for (const block of out.split('\x00')) {
    const files = [...new Set(block.split(/\r?\n/).map((l) => l.trim()).filter(Boolean))];
    if (files.length > BULK_COMMIT || !files.includes(rel)) {
      continue;
    }
    for (const f of files) {
      if (f === rel) {
        continue;
      }
      counts.set(f, (counts.get(f) ?? 0) + 1);
    }
  }
  return [...counts.entries()]
    .map(([f, commits]) => ({ file: f, commits }))
    .filter((c) => c.commits >= 2 || counts.size <= 3)
    .sort((a, b) => b.commits - a.commits || a.file.localeCompare(b.file))
    .slice(0, 5);
}

/** Files that differ between two commits — the changed set after a branch switch. */
export async function changedBetween(
  repoRoot: string,
  fromSha: string,
  toSha: string
): Promise<string[] | undefined> {
  const out = await run(['diff', '--name-only', `${fromSha}..${toSha}`], repoRoot);
  if (!out.trim()) {
    // Empty is ambiguous: no changes, or an unknown commit. Verify the base exists.
    const known = await run(['rev-parse', '--verify', '--quiet', `${fromSha}^{commit}`], repoRoot, 4000);
    return known.trim() ? [] : undefined;
  }
  return out.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
}

/** Paths with uncommitted edits, which no commit SHA can vouch for. */
export async function dirtyFiles(repoRoot: string): Promise<string[]> {
  const out = await run(['status', '--porcelain'], repoRoot, 8000);
  return out
    .split(/\r?\n/)
    .map((l) => l.slice(3).trim())
    .filter(Boolean)
    .map((p) => (p.includes(' -> ') ? p.split(' -> ')[1] : p));
}
